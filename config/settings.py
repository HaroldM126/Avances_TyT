def _mysql_options():
    options = {'charset': 'utf8mb4'}
    ssl_ca = os.getenv('DB_SSL_CA', '').strip()
    ssl_mode = os.getenv('DB_SSL_MODE', '').strip().upper()
    ssl_enabled = os.getenv('DB_SSL', '').strip().lower() in ('1', 'true', 'yes', 'si')

    if ssl_ca:
        if 'BEGIN CERTIFICATE' in ssl_ca:
            ca_path = Path(tempfile.gettempdir()) / 'tyt-db-ca.pem'
            ca_path.write_text(ssl_ca.replace('\\n', '\n'), encoding='utf-8')
            ssl_ca = str(ca_path)
        ssl_cfg = {'ca': ssl_ca}
        if ssl_mode == 'VERIFY_IDENTITY':
            ssl_cfg['check_hostname'] = True
        options['ssl'] = ssl_cfg
    elif ssl_mode in ('VERIFY_CA', 'VERIFY_IDENTITY'):
        import ssl as ssl_lib
        options['ssl'] = {
            'ca': os.getenv('SSL_CERT_FILE') or ssl_lib.get_default_verify_paths().cafile,
            'check_hostname': ssl_mode == 'VERIFY_IDENTITY',
        }
    elif ssl_enabled or ssl_mode == 'REQUIRED':
        options['ssl'] = {'check_hostname': False}
    return options


